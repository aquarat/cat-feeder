#!/usr/bin/env python3
"""Generate schematic, placed (unrouted) PCB, project rules and DSN for one D34 board.

    /usr/bin/python3 build.py ctrl|pwr        (inside cat-feeder-kicad:local)

Generated files are overwritten; design.py and catalog.py are the sources.
"""
import json, math, pathlib, shutil, sys
import pcbnew as p
import d34lib as L
from d34lib import q, uid
import catalog, design

ROOT = L.ROOT
LIBDIR = ROOT / 'd34.pretty'


def xy(x, y): return p.VECTOR2I(p.FromMM(x), p.FromMM(y))


# ------------------------------------------------------------ symbols
def symbol_for(part):
    c = catalog.get(part)
    s = c['sym']
    if isinstance(s, str):
        return s, L.libsymbol(s)
    name, left, right = s  # custom box
    return 'd34:' + name, L.box_symbol(name, left, right, c.get('title'))


def sym_pins(sym):
    pins = []
    for sub in L.kids(sym, 'symbol'):
        for pin in L.kids(sub, 'pin'):
            at = L.kid(pin, 'at')
            pins.append(dict(number=L.unq(L.kid(pin, 'number')[1]), name=L.unq(L.kid(pin, 'name')[1]),
                             type=pin[1], x=float(at[1]), y=float(at[2]), angle=float(at[3])))
    return pins


def make_schematic(B, outdir):
    sheet = uid(B.name, 'sheet')
    libs = {}
    placed = []
    for a in B.parts:
        libid, sym = symbol_for(a)
        libs[libid] = sym
        placed.append((a, libid, sym_pins(sym)))
    # Power-flag every net that has power_in pins but no power_out pin.
    types = {}
    for a, libid, pins in placed:
        for pin in pins:
            n = a.nets.get(pin['number'])
            if n: types.setdefault(n, set()).add(pin['type'])
    flags = sorted(n for n, t in types.items() if 'power_in' in t and 'power_out' not in t)
    flags = sorted(set(flags) | set(B.extra_pwr_flags))
    if flags: libs['power:PWR_FLAG'] = L.libsymbol('power:PWR_FLAG')
    out = [f'''(kicad_sch (version 20250114) (generator "eeschema") (generator_version "9.0")
  (uuid "{sheet}") (paper "A2")
  (title_block (title {q(B.title)}) (date "2026-10-26") (rev {q(B.rev)})
   (comment 1 {q(B.comment1)}) (comment 2 {q(B.comment2)}) (comment 3 "Generated by electronics/d34/build.py from design.py - do not hand-edit"))
  (lib_symbols {' '.join(L.dump(s) for s in libs.values())})''']
    # Flow layout by group; each group starts a new row band with a heading.
    x0, y0, xmax = 25.4, 30.48, 560.0
    x, y, rowh = x0, y0, 0
    group = None
    for a, libid, pins in placed:
        if a.group != group:
            if group is not None:
                x = x0; y += rowh + 12.7; rowh = 0
            group = a.group
            out.append(f'(text {q(group)} (exclude_from_sim no) (at {x0:.2f} {y - 7.62:.2f} 0) (effects (font (size 2.5 2.5) (thickness 0.4) bold) (justify left bottom)) (uuid "{uid(B.name, "grp", group)}"))')
        xs = [pp['x'] for pp in pins]; ys = [pp['y'] for pp in pins]
        lab = max([len(n) for n in a.nets.values()] + [3]) * 1.0 + 6
        w = (max(xs) - min(xs) if xs else 10) + 2 * lab + 8
        h = (max(ys) - min(ys) if ys else 5) + 12
        if x + w > xmax:
            x = x0; y += rowh + 7.62; rowh = 0
        cx = round(round((x + lab - min(xs) + 2.54) / 2.54) * 2.54, 2)
        cy = round(round((y + max(ys) + 5.08) / 2.54) * 2.54, 2)
        x += w; rowh = max(rowh, h)
        top = cy - max(ys) if ys else cy
        props = [f'(property "Reference" {q(a.ref)} (at {cx:.2f} {top - 5.08:.2f} 0) (effects (font (size 1.27 1.27))))',
                 f'(property "Value" {q(a.value)} (at {cx:.2f} {top - 2.54:.2f} 0) (effects (font (size 1.0 1.0))))',
                 f'(property "Footprint" {q("d34:" + catalog.get(a)["fp"].split(":")[1])} (at {cx:.2f} {cy:.2f} 0) (effects (font (size 1 1)) (hide yes)))',
                 f'(property "MPN" {q(catalog.get(a).get("mpn", ""))} (at {cx:.2f} {cy:.2f} 0) (effects (font (size 1 1)) (hide yes)))']
        out.append(f'''(symbol (lib_id {q(libid)}) (at {cx:.2f} {cy:.2f} 0) (unit 1) (exclude_from_sim no)
  (in_bom yes) (on_board yes) (dnp no) (uuid "{uid(B.name, a.ref)}") {' '.join(props)}
  (instances (project {q(B.name)} (path "/{sheet}" (reference {q(a.ref)}) (unit 1)))))''')
        for pin in pins:
            px = round(cx + pin['x'], 2); py = round(cy - pin['y'], 2)
            net = a.nets.get(pin['number'])
            if net is None:
                out.append(f'(no_connect (at {px:.2f} {py:.2f}) (uuid "{uid(B.name, a.ref, pin["number"], "nc")}"))')
                continue
            ang = pin['angle']
            ex = round(px - 2.54 * math.cos(math.radians(ang)), 2)
            ey = round(py + 2.54 * math.sin(math.radians(ang)), 2)
            out.append(f'(wire (pts (xy {px:.2f} {py:.2f}) (xy {ex:.2f} {ey:.2f})) (stroke (width 0) (type default)) (uuid "{uid(B.name, a.ref, pin["number"], "w")}"))')
            la = 0 if ang in (0, 90, 270) else 180
            out.append(f'(label {q(net)} (at {ex:.2f} {ey:.2f} {la}) (effects (font (size 1.0 1.0)) (justify left bottom)) (uuid "{uid(B.name, a.ref, pin["number"], "l")}"))')
    y += rowh + 15
    for i, net in enumerate(flags):
        fx = round(round((x0 + 30 * i) / 2.54) * 2.54, 2); fy = round(round(y / 2.54) * 2.54, 2); ref = f'#FLG{i + 1:02d}'
        out.append(f'''(symbol (lib_id "power:PWR_FLAG") (at {fx:.2f} {fy:.2f} 0) (unit 1) (exclude_from_sim no)
  (in_bom no) (on_board yes) (dnp no) (uuid "{uid(B.name, ref)}")
  (property "Reference" "{ref}" (at {fx:.2f} {fy:.2f} 0) (effects (font (size 1 1)) (hide yes)))
  (property "Value" "PWR_FLAG" (at {fx:.2f} {fy - 4:.2f} 0) (effects (font (size 1 1))))
  (instances (project {q(B.name)} (path "/{sheet}" (reference "{ref}") (unit 1)))))
(label {q(net)} (at {fx:.2f} {fy:.2f} 0) (effects (font (size 1 1)) (justify left bottom)) (uuid "{uid(B.name, ref, 'l')}"))''')
    for i, line in enumerate(B.notes):
        out.append(f'(text {q(line)} (exclude_from_sim no) (at {x0:.2f} {y + 12 + 4 * i:.2f} 0) (effects (font (size 1.8 1.8)) (justify left bottom)) (uuid "{uid(B.name, "note", i)}"))')
    out.append(')')
    (outdir / f'{B.name}.kicad_sch').write_text('\n'.join(out) + '\n')
    custom = []
    for k, v in libs.items():
        if k.startswith('d34:'):
            c = L.parse(L.dump(v)); c[1] = q(k.split(':')[1]); custom.append(L.dump(c))
    (outdir / 'd34.kicad_sym').write_text('(kicad_symbol_lib (version 20241209) (generator "d34lib")\n' + '\n'.join(custom) + '\n)\n')
    stock = sorted({k.split(':')[0] for k in libs if not k.startswith('d34:')})
    table = '(sym_lib_table (version 7)\n' + ''.join(
        f'  (lib (name "{lib}") (type "KiCad") (uri "${{KICAD9_SYMBOL_DIR}}/{lib}.kicad_sym") (options "") (descr ""))\n' for lib in stock) + \
        '  (lib (name "d34") (type "KiCad") (uri "${KIPRJMOD}/d34.kicad_sym") (options "") (descr "Generated D34 symbols"))\n)\n'
    (outdir / 'sym-lib-table').write_text(table)
    return flags


# ------------------------------------------------------------ footprints
def ensure_footprints(B):
    LIBDIR.mkdir(exist_ok=True)
    for a in B.parts:
        fp = catalog.get(a)['fp']
        lib, name = fp.split(':')
        dst = LIBDIR / (name + '.kicad_mod')
        if lib == 'd34':
            dst.write_text(catalog.CUSTOM_FP[name]())
        else:
            f = p.FootprintLoad(str(L.KFP / (lib + '.pretty')), name)
            assert f, fp
            for num, drill in catalog.FP_DRILL_FIX.get(name, {}).items():   # datasheet hole sizes (see catalog)
                for pd in f.Pads():
                    if pd.GetNumber() == num:
                        pd.SetDrillSize(p.VECTOR2I(p.FromMM(drill), p.FromMM(drill)))
                        if pd.GetAttribute() == p.PAD_ATTRIB_NPTH:
                            pd.SetSize(p.F_Cu, p.VECTOR2I(p.FromMM(drill), p.FromMM(drill)))
            p.PCB_IO_KICAD_SEXPR().FootprintSave(str(LIBDIR), f)


def load_fp(fp):
    lib, name = fp.split(':')
    f = p.FootprintLoad(str(LIBDIR), name)
    assert f, fp
    return f


def text(b, s, x, y, size=1.2, rot=0, layer=p.F_SilkS, thick=None, mirror=False):
    t = p.PCB_TEXT(b); t.SetText(s); t.SetPosition(xy(x, y)); t.SetTextSize(xy(size, size))
    t.SetTextThickness(p.FromMM(thick or max(0.15, size * 0.15))); t.SetLayer(layer)
    t.SetTextAngle(p.EDA_ANGLE(rot, p.DEGREES_T))
    if mirror: t.SetMirrored(True)
    b.Add(t); return t


def make_board(B, outdir, version):
    b = p.BOARD(); b.SetCopperLayerCount(2)
    ds = b.GetDesignSettings()
    ds.m_MinClearance = p.FromMM(.2); ds.m_CopperEdgeClearance = p.FromMM(.5)
    ox, oy = B.origin
    nets = {}
    # '/NAME' matches eeschema's local-label net names, so schematic parity is exact.
    for name in sorted({n for a in B.parts for n in a.nets.values()}):
        nets[name] = p.NETINFO_ITEM(b, '/' + name); b.Add(nets[name])
    sheet = uid(B.name, 'sheet')
    for a in B.parts:
        c = catalog.get(a)
        f = load_fp(c['fp'])
        f.SetFPID(p.LIB_ID('d34', c['fp'].split(':')[1]))
        f.SetReference(a.ref); f.SetValue(a.value)
        f.SetPosition(xy(ox + a.x, oy + a.y)); f.SetOrientationDegrees(a.rot)
        f.SetPath(p.KIID_PATH('/' + sheet + '/' + uid(B.name, a.ref)))
        f.Value().SetVisible(False)
        for item in list(f.GraphicalItems()) + list(f.GetFields()):   # stock 'K'/'+' marker texts collide; stripes remain
            if isinstance(item, (p.PCB_TEXT, p.PCB_FIELD)) and item is not f.Reference() and item.GetText() not in (a.ref,) \
                    and item.GetLayer() in (p.F_SilkS, p.B_SilkS):
                item.SetLayer(p.F_Fab)
        r = f.Reference(); r.SetTextSize(xy(1.0, 1.0)); r.SetTextThickness(p.FromMM(.15))
        if a.ref_at == 'hide':   # no room: reference shown on F.Fab / assembly view only
            r.SetLayer(p.F_Fab)
        elif a.ref_at is not None:
            rx, ry, rr = a.ref_at
            r.SetPosition(xy(ox + rx, oy + ry)); r.SetTextAngle(p.EDA_ANGLE(rr, p.DEGREES_T))
        pinname = {pp['number']: pp['name'] for pp in sym_pins(symbol_for(a)[1])}
        for pad in f.Pads():
            n = a.nets.get(pad.GetNumber())
            if n: pad.SetNet(nets[n])
            elif pad.GetNumber() in pinname:   # eeschema names no-connect pins this way
                nm = pinname[pad.GetNumber()].replace('/', '{slash}')
                nm = '' if nm in ('~', '') else nm + '-'
                nc = p.NETINFO_ITEM(b, f'unconnected-({a.ref}-{nm}Pad{pad.GetNumber()})'); b.Add(nc); pad.SetNet(nc)
            if n and n in B.solid_pads:
                pad.SetLocalZoneConnection(p.ZONE_CONNECTION_FULL)
        b.Add(f)
    # Rectangular outline with 1 mm corner radius.
    W, H, R = B.width, B.height, 1.0
    for (x1, y1, x2, y2) in [(R, 0, W - R, 0), (W, R, W, H - R), (W - R, H, R, H), (0, H - R, 0, R)]:
        s = p.PCB_SHAPE(); s.SetShape(p.SHAPE_T_SEGMENT); s.SetStart(xy(ox + x1, oy + y1)); s.SetEnd(xy(ox + x2, oy + y2))
        s.SetLayer(p.Edge_Cuts); s.SetWidth(p.FromMM(.1)); b.Add(s)
    for cx, cy, sx, sy in [(R, R, 0, R), (W - R, R, W - R, 0), (W - R, H - R, W, H - R), (R, H - R, R, H)]:
        s = p.PCB_SHAPE(); s.SetShape(p.SHAPE_T_ARC); s.SetCenter(xy(ox + cx, oy + cy)); s.SetStart(xy(ox + sx, oy + sy))
        s.SetArcAngleAndEnd(p.EDA_ANGLE(90, p.DEGREES_T), True); s.SetLayer(p.Edge_Cuts); s.SetWidth(p.FromMM(.1)); b.Add(s)
    # Cradle edge bands documented on a user layer (no copper restriction: mask covers pour).
    for y1, y2 in [(0, B.band), (H - B.band, H)]:
        s = p.PCB_SHAPE(); s.SetShape(p.SHAPE_T_RECT); s.SetStart(xy(ox, oy + y1)); s.SetEnd(xy(ox + W, oy + y2))
        s.SetLayer(p.Dwgs_User); s.SetWidth(p.FromMM(.1)); b.Add(s)
    # 0.7 mm via/track keep-out round the edge: Freerouting ignores the DRU edge rule.
    W_, H_ = B.width, B.height
    for (x1, y1, x2, y2) in [(0, 0, W_, 0.7), (0, H_ - 0.7, W_, H_), (0, 0, 0.7, H_), (W_ - 0.7, 0, W_, H_)]:
        z = p.ZONE(b); z.SetIsRuleArea(True); ls = p.LSET(); ls.AddLayer(p.F_Cu); ls.AddLayer(p.B_Cu); z.SetLayerSet(ls)
        z.SetDoNotAllowTracks(True); z.SetDoNotAllowVias(True); z.SetDoNotAllowCopperPour(False); z.SetDoNotAllowPads(False)
        z.SetDoNotAllowFootprints(False); z.SetZoneName('edge keep-out'); z.Outline().NewOutline()
        for px, py in [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]: z.Outline().Append(p.FromMM(ox + px), p.FromMM(oy + py))
        b.Add(z)
    for ko in B.keepouts:
        (x1, y1, x2, y2, name), tracks_only = ko[:5], (len(ko) > 5 and ko[5] == 'tracks')
        z = p.ZONE(b); z.SetIsRuleArea(True); ls = p.LSET(); ls.AddLayer(p.F_Cu); ls.AddLayer(p.B_Cu); z.SetLayerSet(ls)
        z.SetDoNotAllowTracks(True); z.SetDoNotAllowVias(True); z.SetDoNotAllowCopperPour(not tracks_only); z.SetDoNotAllowPads(not tracks_only)
        z.SetDoNotAllowFootprints(False); z.SetZoneName(name); z.Outline().NewOutline()
        for px, py in [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]: z.Outline().Append(p.FromMM(ox + px), p.FromMM(oy + py))
        b.Add(z)
    for t in B.silk:
        s, x, y = t[:3]; kw = t[3] if len(t) > 3 else {}
        layer = p.B_SilkS if kw.get('back') else p.F_SilkS
        text(b, s, ox + x, oy + y, kw.get('size', 1.2), kw.get('rot', 0), layer, mirror=kw.get('back', False))
    vx, vy = B.version_at
    # D30 version identifier on the back silkscreen: source digest of the generator inputs.
    text(b, f'{B.title_short} {B.rev} src {version[:12]}', ox + vx, oy + vy, 1.0, layer=p.B_SilkS, mirror=True)
    for (net, layer, width, pts) in B.preroutes:
        lay = p.F_Cu if layer == 'F' else p.B_Cu
        for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
            t = p.PCB_TRACK(b); t.SetStart(xy(ox + x1, oy + y1)); t.SetEnd(xy(ox + x2, oy + y2)); t.SetLayer(lay)
            t.SetWidth(p.FromMM(width)); t.SetNet(nets[net]); t.SetLocked(True); b.Add(t)
    b.GetDesignSettings().SetAuxOrigin(xy(ox, oy + H))
    b.GetDesignSettings().SetGridOrigin(xy(ox, oy + H))
    path = outdir / f'{B.name}-unrouted.kicad_pcb'
    save_board(path, b, B)
    p.ExportSpecctraDSN(b, str(outdir / f'{B.name}.dsn'))
    patch_dsn(outdir / f'{B.name}.dsn', B)
    return b


# ------------------------------------------------------------ project
def project_json(B):
    def cls(name, w, clr, via=(0.8, 0.4)):
        return dict(name=name, clearance=clr, track_width=w, via_diameter=via[0], via_drill=via[1],
                    diff_pair_width=0.2, diff_pair_gap=0.25, diff_pair_via_gap=0.25,
                    microvia_diameter=0.3, microvia_drill=0.1, wire_width=6, bus_width=12)
    classes = [cls('Default', B.default_track, 0.2)]
    pats = []
    for name, spec in B.netclasses.items():
        classes.append(cls(name, spec['width'], spec['clearance'], spec.get('via', (0.8, 0.4))))
        for n in spec['nets']:
            pats.append({'pattern': n, 'netclass': name}); pats.append({'pattern': '/' + n, 'netclass': name})
    return {'meta': {'filename': f'{B.name}.kicad_pro', 'version': 1},
            'board': {'design_settings': {
                'rules': {'min_clearance': 0.2, 'min_track_width': 0.2, 'min_via_diameter': 0.6,
                          'min_through_hole_diameter': 0.3, 'min_copper_edge_clearance': 0.5,
                          'min_hole_clearance': 0.35, 'min_silk_clearance': 0.15,
                          'min_text_height': 1.0, 'min_text_thickness': 0.15},
                'rule_severities': {}}},
            'net_settings': {'classes': classes, 'netclass_patterns': pats},
            'libraries': {'pinned_footprint_libs': [], 'pinned_symbol_libs': []}}


def save_board(path, b, B):
    """pcbnew's headless SaveBoard can rewrite the project; restore ours."""
    path = pathlib.Path(path)
    proj = path.with_suffix('.kicad_pro')
    data = json.dumps(project_json(B), indent=2) + '\n'
    proj.write_text(data)
    p.SaveBoard(str(path), b)
    proj.write_text(data)


def patch_dsn(path, B):
    """Give Freerouting the net-class widths (exporter uses defaults headlessly)."""
    import re
    dsn = path.read_text()
    # 0.8/0.4 mm vias: KiCad's SES importer reads size/drill back from this name.
    old = re.search(r'\(via\s+"?([^\s)"]+)"?', dsn).group(1)
    dsn = dsn.replace(old, 'Via[0-1]_800:400_um')
    dsn = re.sub(r'(\(padstack "?Via\[0-1\]_800:400_um"?\s*\(shape \(circle F\.Cu )\d+', r'\g<1>800', dsn)
    dsn = re.sub(r'(\(shape \(circle B\.Cu )600', r'\g<1>800', dsn)
    assigned = {'/' + n for spec in B.netclasses.values() for n in spec['nets']}
    m = re.search(r'\(class kicad_default(.*?)\(circuit', dsn, re.S)
    keep = [n for n in m.group(1).split() if n.strip('"') not in assigned]
    dsn = dsn[:m.start(1)] + ' ' + ' '.join(keep) + '\n      ' + dsn[m.end(1):]
    dsn = re.sub(r'(\(class kicad_default.*?\(rule\s*\(width )\d+(\)\s*\(clearance )\d+',
                 lambda k: f'{k.group(1)}{B.default_track * 1000:.0f}{k.group(2)}200', dsn, count=1, flags=re.S)
    marker = '\n  (wiring'; end = dsn.index(marker); network_end = dsn.rfind(')', 0, end)
    classes = ''
    for name, spec in B.netclasses.items():
        names = ' '.join('/' + n for n in spec['nets'])
        classes += (f'\n    (class {name.lower()} {names} (circuit (use_via "Via[0-1]_800:400_um")) '
                    f'(rule (width {spec["width"] * 1000:.0f}) (clearance {spec["clearance"] * 1000:.0f})))')
    dsn = dsn[:network_end] + classes + '\n  ' + dsn[network_end:]
    path.write_text(dsn)


def main(board):
    B = design.BOARDS[board]()
    outdir = ROOT / B.name; outdir.mkdir(exist_ok=True)
    sources = [ROOT / f for f in ('design.py', 'catalog.py', 'd34lib.py', 'build.py')]
    version = L.source_digest(sources)
    ensure_footprints(B)
    flags = make_schematic(B, outdir)
    make_board(B, outdir, version)
    (outdir / 'fp-lib-table').write_text('(fp_lib_table (version 7)\n  (lib (name "d34") (type "KiCad") (uri "${KIPRJMOD}/../d34.pretty") (options "") (descr "D34 footprints: KiCad 9.0.2 stock copies plus generated module sockets"))\n)\n')
    shutil.copy(ROOT.parent / 'dfm' / 'jlcpcb-2layer-recommended.kicad_dru', outdir / f'{B.name}.kicad_dru')
    for suffix in ('-unrouted',):
        shutil.copy(outdir / f'{B.name}.kicad_dru', outdir / f'{B.name}{suffix}.kicad_dru')
    (outdir / f'{B.name}.kicad_pro').write_text(json.dumps(project_json(B), indent=2) + '\n')
    meta = {'board': B.name, 'source_sha256': version, 'size_mm': [B.width, B.height], 'pwr_flags': flags,
            'parts': [dict(ref=a.ref, kind=a.kind, value=a.value, nets=a.nets, x=a.x, y=a.y, rot=a.rot) for a in B.parts],
            'connectors': B.connectors, 'netclasses': B.netclasses, 'band_mm': B.band}
    (outdir / 'design.json').write_text(json.dumps(meta, indent=1) + '\n')
    print(f'{B.name}: {len(B.parts)} parts, {len({n for a in B.parts for n in a.nets.values()})} nets, src {version[:12]}')


if __name__ == '__main__':
    main(sys.argv[1])
